"""
\n New line
 \t Tab space
 \\ print a backslash
\' print a single quote
 \" print a double quote
"""


print("Hello\nWorld")  # New line

print("hello\tworld") # Tab space

print("s\\\\\\hah") # print a backslash

#my name is "shah" g

print("my name is \"shah\" g") # print a double quote

print('my name is \'shah\' g') # print a single quote